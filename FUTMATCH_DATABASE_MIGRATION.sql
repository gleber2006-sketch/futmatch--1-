-- Function: Criar partida com tokens (custo: 3 tokens)
CREATE OR REPLACE FUNCTION public.create_match_with_tokens(
  p_name text,
  p_sport text,
  p_location text,
  p_lat real,
  p_lng real,
  p_date timestamp with time zone,
  p_slots int,
  p_rules text,
  p_is_private boolean,
  p_invite_code text,
  p_team_id BIGINT DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user_id uuid;
  v_balance int;
  v_new_match_id bigint;
  v_match_data jsonb;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'NOT_AUTHENTICATED';
  END IF;

  -- Verificar saldo
  SELECT balance INTO v_balance FROM public.tokens WHERE user_id = v_user_id;
  IF v_balance IS NULL OR v_balance < 3 THEN
    RAISE EXCEPTION 'INSUFFICIENT_FUNDS';
  END IF;

  -- 1. Deduzir tokens
  UPDATE public.tokens SET balance = balance - 3 WHERE user_id = v_user_id;

  -- 2. Criar partida
  INSERT INTO public.matches (
    created_by, name, sport, location, lat, lng, date, slots, rules, is_private, invite_code, team_id
  ) VALUES (
    v_user_id, p_name, p_sport, p_location, p_lat, p_lng, p_date, p_slots, p_rules, p_is_private, p_invite_code, p_team_id
  ) RETURNING id INTO v_new_match_id;

  -- 3. Retornar dados da partida criada
  SELECT to_jsonb(m) INTO v_match_data FROM public.matches m WHERE id = v_new_match_id;
  
  RETURN v_match_data;
END;
$$;


-- Function: Entrar na partida (custo: 1 token)
CREATE OR REPLACE FUNCTION public.join_match_with_token(p_match_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user_id uuid;
  v_balance int;
  v_match record;
  v_is_participant boolean;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RETURN 'NOT_AUTHENTICATED';
  END IF;

  -- Verificar status da partida
  SELECT * INTO v_match FROM public.matches WHERE id = p_match_id;
  IF v_match IS NULL THEN
    RETURN 'MATCH_NOT_FOUND';
  END IF;
  
  IF v_match.status != 'Convocando' THEN
    RETURN 'MATCH_CLOSED';
  END IF;
  
  IF v_match.filled_slots >= v_match.slots THEN
    RETURN 'MATCH_FULL';
  END IF;

  -- Verificar se jÃ¡ estÃ¡ na partida
  SELECT EXISTS(SELECT 1 FROM public.match_participants WHERE match_id = p_match_id AND user_id = v_user_id) INTO v_is_participant;
  IF v_is_participant THEN
    RETURN 'ALREADY_IN';
  END IF;

  -- Verificar saldo de tokens
  SELECT balance INTO v_balance FROM public.tokens WHERE user_id = v_user_id;
  IF v_balance IS NULL OR v_balance < 1 THEN
    RETURN 'NO_TOKENS';
  END IF;

  -- EXECUTAR TRANSAÃ‡ÃƒO
  -- 1. Deduzir token
  UPDATE public.tokens SET balance = balance - 1 WHERE user_id = v_user_id;
  
  -- 2. Adicionar participante
  INSERT INTO public.match_participants (match_id, user_id) VALUES (p_match_id, v_user_id);

  RETURN 'OK';
END;
$$;


-- Function: Sair da partida (reembolso: 1 token)
CREATE OR REPLACE FUNCTION public.leave_match_with_refund(p_match_id bigint)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user_id uuid;
  v_deleted_count int;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RETURN 'NOT_AUTHENTICATED';
  END IF;

  -- Deletar participante e verificar se houve exclusÃ£o
  WITH deleted AS (
    DELETE FROM public.match_participants 
    WHERE match_id = p_match_id AND user_id = v_user_id
    RETURNING *
  )
  SELECT count(*) INTO v_deleted_count FROM deleted;

  IF v_deleted_count = 0 THEN
    RETURN 'NOT_IN_MATCH';
  END IF;

  -- Reembolsar token
  UPDATE public.tokens SET balance = balance + 1 WHERE user_id = v_user_id;

  RETURN 'OK';
END;
$$;


-- Function: Cancelar partida
CREATE OR REPLACE FUNCTION public.cancel_match(p_match_id bigint, p_user_id uuid, p_reason text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  UPDATE public.matches
  SET
