RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.tokens (user_id, balance)
  VALUES (p_user_id, amount)
  ON CONFLICT (user_id)
  DO UPDATE SET balance = tokens.balance + amount, updated_at = now();
END;
$$;


